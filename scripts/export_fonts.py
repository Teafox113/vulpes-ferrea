"""
Vulpes Ferrea — build every deliverable from sources/glyphs.json.

Outputs:
  fonts/otf/VulpesFerrea-Regular.otf          CFF outlines, for desktop apps
  fonts/ttf/VulpesFerrea-Regular.ttf          TrueType, autohinted with ttfautohint
  fonts/webfonts/VulpesFerrea-Regular.woff2   web font (compressed from the hinted TTF)
  sources/VulpesFerrea-Regular.ufo/           UFO for font editors (FontForge, FontLab, Fontra)
  documentation/specimen.html|png, webtest.html, check.md

Only fonttools is required. ttfautohint-py, brotli, ufoLib2, Pillow and opentype-sanitizer
are optional; anything missing is skipped and noted in documentation/check.md.
Returns the list of spec violations (non-empty = failure).

    python scripts/export_fonts.py      # rebuild fonts without regenerating outlines
"""
import base64
import json
import math
import os
import sys

UPM = 1000
# 固定時間戳，讓同一份原始檔每次建出位元組相同的字型檔，git 才不會因為重建而出現假變更。
os.environ.setdefault("SOURCE_DATE_EPOCH", "1794528000")  # 2026-11-13 00:00 UTC
PS = "VulpesFerrea-Regular"
VERSION = 0.310


def check(data, diag, exempt):
    """規範自檢：§5.5 角度、§5.6 格點、行框。"""
    issues, warn = [], []
    for name, g in data.items():
        for c in g["contours"]:
            for i, (x, y) in enumerate(c):
                x2, y2 = c[(i + 1) % len(c)]
                ang = math.degrees(math.atan2(y2 - y, x2 - x)) % 45
                if min(ang, 45 - ang) > 0.01 and name not in diag and name not in exempt:
                    issues.append(f"{name}: 非 0/45/90 線段 ({x},{y})→({x2},{y2})")
                if x % 15 or y % 15:
                    if name in exempt:
                        if x % 7.5 or y % 7.5:
                            issues.append(f"{name}: 縮放字離 7.5 格點 ({x},{y})")
                    elif name in diag:
                        warn.append(f"{name}: 斜畫交點 ({x},{y})")
                    elif name not in ("i", "j"):
                        issues.append(f"{name}: 離格點 ({x},{y})")
        ys = [p[1] for c in g["contours"] for p in c]
        if ys and (min(ys) < -260 or max(ys) > 900):
            issues.append(f"{name}: 超出行框（{min(ys)}..{max(ys)}）")
    return issues, warn


def names_version():
    return f"Version {VERSION:.3f}"


def path_d(g, ox=0.0, oy=0.0):
    return "".join("M" + " L".join(f"{x + ox:g} {y + oy:g}" for x, y in c) + "Z" for c in g["contours"])


